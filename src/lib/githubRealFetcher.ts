export function parseGitHubUrl(url: string): { owner: string; repo: string } | null {
  if (!url) return null;
  const clean = url
    .trim()
    .replace(/^https?:\/\//i, "")
    .replace(/^www\./i, "")
    .replace(/^github\.com\//i, "");
  const parts = clean.split("/").filter(Boolean);
  if (parts.length >= 2) {
    return {
      owner: parts[0],
      repo: parts[1].replace(/\.git$/i, ""),
    };
  }
  return null;
}

/**
 * Filter out build artifacts, dist, node_modules, and lockfiles
 */
function isSourceCodeFile(filePath: string): boolean {
  const lower = filePath.toLowerCase();
  const excluded = [
    "node_modules",
    "dist",
    "build",
    ".next",
    "out",
    ".git",
    "vendor",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "bun.lockb",
    ".min.js",
    ".map",
    ".d.ts",
    "components.json",
    "eslint.config",
    "postcss.config",
    "tailwind.config",
    "vite.config",
  ];
  for (const ex of excluded) {
    if (lower.includes(ex)) return false;
  }
  return /\.(tsx|ts|jsx|js|py|go|rs|java|cpp|cs)$/i.test(filePath);
}

/**
 * Line by line code annotator for real source code
 */
function annotateLines(code: string, fileName: string): InspectedCodeLine[] {
  const rawLines = code.split("\n");
  // Limit to first 45 lines for clean, readable inspector UI
  const displayLines = rawLines.slice(0, 45);

  return displayLines.map((line, idx) => {
    const trimmed = line.trim();
    let isAi = false;
    let annotation = "";

    if (trimmed.startsWith("import ")) {
      annotation = "Import dependency";
    } else if (trimmed.startsWith("export interface") || trimmed.startsWith("interface ") || trimmed.startsWith("type ")) {
      annotation = "Type contract definition";
    } else if (trimmed.includes("useState") || trimmed.includes("useEffect") || trimmed.includes("useRef") || trimmed.includes("useMemo")) {
      annotation = "React Hook state management";
    } else if (trimmed.includes("useCart") || trimmed.includes("useLanguage") || trimmed.includes("useNavigate") || trimmed.includes("useToast")) {
      annotation = "Custom Domain Context dispatch";
    } else if (trimmed.startsWith("export function") || trimmed.startsWith("export const") || trimmed.includes("function ")) {
      annotation = "Domain component definition";
    } else if (trimmed.includes("return (") || trimmed.includes("<div") || trimmed.includes("<Button") || trimmed.includes("<span")) {
      annotation = "Interactive UI markup";
    } else if (trimmed.includes("onClick") || trimmed.includes("onChange") || trimmed.includes("onSubmit")) {
      annotation = "Client interaction event handler";
    } else if (trimmed.startsWith("//") || trimmed.startsWith("/*") || trimmed.startsWith("*")) {
      if (/generated by|ai prompt|chatgpt|copilot/i.test(trimmed)) {
        isAi = true;
        annotation = "AI Watermark signature";
      } else {
        annotation = "Developer inline documentation";
      }
    } else if (trimmed.length > 0) {
      annotation = "Application logic statement";
    }

    return {
      lineNum: idx + 1,
      code: line,
      isAi,
      annotation: annotation || undefined,
    };
  });
}

